import AemiJSONCore
import Foundation

// https://html.spec.whatwg.org/entities.json: {"&AElig;": {"codepoints": [198], "characters": "Æ"}, "&AElig": {...}, ...}.
// CommonMark recognises only the names that end in a semicolon, so the legacy names without one are dropped.
guard CommandLine.arguments.count == 2, let data = FileManager.default.contents(atPath: CommandLine.arguments[1]) else {
    FileHandle.standardError.write(Data("usage: GenerateEntities entities.json\n".utf8))
    exit(2)
}
let document = try AemiJSON.parse(Array(data))
var entries: [(name: String, codepoints: [Int])] = []
document.root.forEachMember { key, value in
    guard key.hasPrefix("&"), key.hasSuffix(";") else { return }
    let codepoints = value["codepoints"].arrayValue.map { $0.intValue }
    entries.append((String(key.dropFirst().dropLast()), codepoints))
}
entries.sort { Array($0.name.utf8).lexicographicallyPrecedes(Array($1.name.utf8)) }

var out = """
    // Generated by Plugins/GenerateEntities from https://html.spec.whatwg.org/entities.json. Do not edit.
    //
    // One entity per line: its name without `&` and `;`, then its code points in hex, sorted by name bytes.

    extension EntityTable {
        static let data: StaticString = \"\"\"

    """
for entry in entries {
    out += entry.name + " " + entry.codepoints.map { String($0, radix: 16) }.joined(separator: " ") + "\n"
}
out += "\"\"\"\n}\n"
print(out, terminator: "")
